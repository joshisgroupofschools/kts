function splitInstallmentAmounts(total: number, count: number): number[] {
  if (count <= 0 || total <= 0) return Array(Math.max(1, count)).fill(0);
  const base = Math.floor(total / count);
  const remainder = total - (base * count);
  const result: number[] = [];
  for (let i = 0; i < count; i++) {
    result.push(i === 0 ? base + remainder : base);
  }
  return result;
}

export function generateStructuredRealData() {
  const students: Student[] = [];
  const feeStructures: StudentFeeStructure[] = [];
  const installments: Installment[] = [];
  const payments: PaymentTransaction[] = [];
  const nowStr = new Date().toISOString();

  REAL_SPREADSHEET_ROWS.forEach((row) => {
    const studentId = row.studentId;
    const classId = "cls_" + row.className.toLowerCase().replace(/\s+/g, "_");
    const standardClassFee = lookupStandardClassFee(row.className || row.rawClass);
    const committedSchoolFee = row.schoolFee > 0 ? row.schoolFee : standardClassFee;
    const actualSchoolFee = standardClassFee;
    const concessionAmount = Math.max(0, actualSchoolFee - committedSchoolFee);

    const student: Student = {
      id: studentId,
      name: row.name,
      rollNo: row.rollNo,
      classId,
      className: row.className,
      section: "A",
      parentName: "",
      phone: "98" + String(10000000 + row.sNo).slice(0, 8),
      admissionDate: "2026-06-01",
      isActive: true,
      notes: row.commitReceipt ? ("Commitment Receipt #" + row.commitReceipt) : undefined,
      createdAt: nowStr,
      updatedAt: nowStr,
    };
    students.push(student);

    // 1. School Fee Head (7 Installments: July 10 to Jan 10)
    if (committedSchoolFee > 0) {
      const fsSchoolId = "fs_sch_" + studentId;
      feeStructures.push({
        id: fsSchoolId,
        studentId,
        headName: "School Tuition Fee",
        actualFee: actualSchoolFee,
        committedFee: committedSchoolFee,
        concession: concessionAmount,
        concessionReason: concessionAmount > 0 ? "Annual Fee Concession / Scholarship" : undefined,
        commitmentDate: "2026-06-15",
        commitmentReceiptNo: row.commitReceipt || undefined,
        installmentsCount: 7,
        isSpotFee: false,
      });

      const schoolAmounts = splitInstallmentAmounts(committedSchoolFee, 7);
      schoolAmounts.forEach((amt, i) => {
        installments.push({
          id: "inst_sch_" + studentId + "_" + (i + 1),
          feeStructureId: fsSchoolId,
          studentId,
          headName: "School Tuition Fee",
          installmentNumber: i + 1,
          totalInstallments: 7,
          amount: amt,
          dueDate: SCHOOL_FEE_DUE_DATES[i],
          paidAmount: 0,
          balanceAmount: amt,
          status: "unpaid",
        });
      });
    }

    // 2. Transport Fee Head (10 Installments: June 10 to March 10)
    if (row.transportFee > 0) {
      const fsTransId = "fs_trans_" + studentId;
      feeStructures.push({
        id: fsTransId,
        studentId,
        headName: "Transport / Bus Fee",
        actualFee: row.transportFee,
        committedFee: row.transportFee,
        concession: 0,
        commitmentDate: "2026-06-15",
        installmentsCount: 10,
        isSpotFee: false,
      });

      const transAmounts = splitInstallmentAmounts(row.transportFee, 10);
      transAmounts.forEach((amt, i) => {
        installments.push({
          id: "inst_trans_" + studentId + "_" + (i + 1),
          feeStructureId: fsTransId,
          studentId,
          headName: "Transport / Bus Fee",
          installmentNumber: i + 1,
          totalInstallments: 10,
          amount: amt,
          dueDate: TRANSPORT_FEE_DUE_DATES[i],
          paidAmount: 0,
          balanceAmount: amt,
          status: "unpaid",
        });
      });
    }

    // 3. Old Due Head (7 Installments: Sept 10 to March 10)
    if (row.oldDueFee > 0) {
      const fsOldId = "fs_old_" + studentId;
      feeStructures.push({
        id: fsOldId,
        studentId,
        headName: "Old Due Carryover",
        actualFee: row.oldDueFee,
        committedFee: row.oldDueFee,
        concession: 0,
        commitmentDate: "2026-06-15",
        installmentsCount: 7,
        isSpotFee: false,
        remarks: "Previous Year Pending Due",
      });

      const oldAmounts = splitInstallmentAmounts(row.oldDueFee, 7);
      oldAmounts.forEach((amt, i) => {
        installments.push({
          id: "inst_old_" + studentId + "_" + (i + 1),
          feeStructureId: fsOldId,
          studentId,
          headName: "Old Due Carryover",
          installmentNumber: i + 1,
          totalInstallments: 7,
          amount: amt,
          dueDate: OLD_DUE_DATES[i],
          paidAmount: 0,
          balanceAmount: amt,
          status: "unpaid",
        });
      });
    }

    // Process Recorded Receipts / Payments from the spreadsheet
    const paymentParts = [];
    const dateParts = row.dateRaw ? row.dateRaw.split(/[_,]/) : [];
    const receiptParts = row.receiptRaw ? row.receiptRaw.split(/[_,]/) : [];
    const modeParts = row.modeRaw ? row.modeRaw.split(/[_,+]/) : [];

    function normalizeMode(m: string): PaymentMode {
      const upper = (m || "").toUpperCase().trim();
      if (upper.includes("ONLINE") || upper.includes("UPI") || upper.includes("NET")) return "UPI";
      if (upper.includes("CHEQUE") || upper.includes("DD")) return "Cheque";
      return "Cash";
    }

    if (row.inst1 > 0) {
      paymentParts.push({
        amount: row.inst1,
        date: dateParts[0] ? dateParts[0] : "15-06-2026",
        receiptNo: receiptParts[0] ? receiptParts[0] : "RCT-" + row.rollNo + "-1",
        mode: normalizeMode(modeParts[0] || row.modeRaw),
      });
    }

    if (row.inst2 > 0) {
      paymentParts.push({
        amount: row.inst2,
        date: dateParts[1] ? dateParts[1] : (dateParts[0] || "27-07-2026"),
        receiptNo: receiptParts[1] ? receiptParts[1] : ("RCT-" + row.rollNo + "-2"),
        mode: normalizeMode(modeParts[1] || modeParts[0] || row.modeRaw),
      });
    }

    if (paymentParts.length === 0 && row.totalPaid > 0) {
      paymentParts.push({
        amount: row.totalPaid,
        date: row.dateRaw || "15-07-2026",
        receiptNo: row.receiptRaw || ("RCT-" + row.rollNo),
        mode: normalizeMode(row.modeRaw),
      });
    }

    paymentParts.forEach((pay, pIdx) => {
      let remToAllocate = pay.amount;
      const studentInsts = installments.filter((ins) => ins.studentId === studentId);
      studentInsts.sort((a, b) => a.dueDate.localeCompare(b.dueDate));

      const allocations: PaymentAllocation[] = [];

      for (const inst of studentInsts) {
        if (remToAllocate <= 0) break;
        const availableInInst = inst.amount - inst.paidAmount;
        if (availableInInst > 0) {
          const allocation = Math.min(remToAllocate, availableInInst);
          inst.paidAmount += allocation;
          inst.balanceAmount = inst.amount - inst.paidAmount;
          remToAllocate -= allocation;
          if (inst.paidAmount >= inst.amount) {
            inst.status = "paid";
          } else {
            inst.status = "partial";
          }
          allocations.push({
            installmentId: inst.id,
            headName: inst.headName,
            installmentNumber: inst.installmentNumber,
            dueDate: inst.dueDate,
            allocatedAmount: allocation,
          });
        }
      }

      payments.push({
        id: "txn_" + studentId + "_" + (pIdx + 1),
        receiptNo: pay.receiptNo,
        studentId,
        studentName: row.name,
        studentRollNo: row.rollNo,
        studentClass: row.className,
        date: "2026-07-15 10:00",
        amount: pay.amount,
        paymentMode: pay.mode,
        referenceNo: row.commitReceipt ? ("Commitment Rct #" + row.commitReceipt) : undefined,
        remarks: "Spreadsheet Import: " + (row.dateRaw ? "Date: " + row.dateRaw : "") + (row.receiptRaw ? " | Ref: " + row.receiptRaw : ""),
        allocations,
        isCancelled: false,
        collectedBy: "Accounts Office",
      });
    });
  });

  return { students, feeStructures, installments, payments };
}
