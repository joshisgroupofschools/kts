export function lookupStandardClassFee(className: string): number {
  if (!className) return 30000;
  const direct = STANDARD_CLASS_FEES[className];
  if (direct !== undefined) return direct;
  const upper = className.trim().toUpperCase();
  if (STANDARD_CLASS_FEES[upper] !== undefined) return STANDARD_CLASS_FEES[upper];
  const cleaned = className.trim().replace(/^Class\s*/i, '').replace(/^Grade\s*/i, '').trim();
  if (STANDARD_CLASS_FEES[cleaned] !== undefined) return STANDARD_CLASS_FEES[cleaned];
  const cleanedUpper = cleaned.toUpperCase();
  if (STANDARD_CLASS_FEES[cleanedUpper] !== undefined) return STANDARD_CLASS_FEES[cleanedUpper];
  return 30000;
}

