function splitInstallmentAmounts(total: number, count: number): number[] {
  if (count <= 0 || total <= 0) return Array(Math.max(1, count)).fill(0);
  const base = Math.floor(total / count);
  const remainder = total - (base * count);
  const result: number[] = [];
  for (let i = 0; i < count; i++) {
    result.push(i === 0 ? base + remainder : base);
  }
  return result;
}

function parseSpreadsheetDate(d: string, fallback: string): string {
  if (!d) return fallback + " 10:00";
  const cleaned = d.trim().replace(/'/g, '');
  const parts = cleaned.split(/[-/]/);
  if (parts.length >= 2) {
    const day = parseInt(parts[0], 10);
    const month = parseInt(parts[1], 10);
    let year = 2026;
    if (parts.length >= 3) {
      const y = parseInt(parts[2], 10);
      year = y < 100 ? 2000 + y : y;
    }
    if (!isNaN(day) && !isNaN(month) && month >= 1 && month <= 12 && day >= 1 && day <= 31) {
      return `${year}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')} 10:00`;
    }
  }
  return fallback + " 10:00";
}

function normalizeMode(m: string): PaymentMode {
  const upper = (m || "").toUpperCase().trim();
  if (upper.includes("ONLINE") || upper.includes("UPI") || upper.includes("NET")) return "UPI";
  if (upper.includes("CHEQUE") || upper.includes("DD")) return "Cheque";
  return "Cash";
}

